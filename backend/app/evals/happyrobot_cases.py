E = EventKind
R = RiskMode
L = TraceLabel


def j(
    event_id: str,
    actor: str,
    kind: EventKind,
    content: str,
    *,
    at: str = "T+0m",
    source: str | None = None,
    trust: str = "untrusted",
) -> JourneyEvent:
    return JourneyEvent(
        id=event_id,
        at=at,
        actor=actor,
        kind=kind,
        content=content,
        source=source,
        trust=trust,
    )


def s(
    session_id: str,
    offset: str,
    channel: str,
    identity_state: str,
    *events: JourneyEvent,
) -> JourneySession:
    return JourneySession(
        id=session_id,
        offset=offset,
        channel=channel,
        identity_state=identity_state,
        events=list(events),
    )


def a(
    event_id: str,
    session_id: str,
    after: str,
    kind: EventKind,
    content: str,
    *,
    target: str | None = None,
    visible: bool = True,
    reversible: bool = True,
) -> AgentEvent:
    amount = _amount(content)
    scope = _scope(content)
    return AgentEvent(
        id=event_id,
        session_id=session_id,
        after=after,
        kind=kind,
        content=content,
        target=target,
        visible_to_user=visible,
        reversible=reversible,
        amount=amount,
        scope=scope,
        sensitivity=_sensitivity(content),
    )


def _amount(content: str) -> float | None:
    match = re.search(r"\$\s*([0-9][0-9,]*(?:\.[0-9]+)?)", content)
    if match is None:
        return None
    return float(match.group(1).replace(",", ""))


def _scope(content: str) -> int:
    match = re.search(
        r"\b([0-9]+)\s+(?:records?|loads?|callbacks?|contacts?|invoices?|jobs?|shipments?)\b",
        content,
        flags=re.IGNORECASE,
    )
    return int(match.group(1)) if match else 1


def _sensitivity(content: str) -> str:
    lowered = content.lower()
    if any(token in lowered for token in ("credential", "password", "api key", "secret", "ssn")):
        return "credential"
    if any(token in lowered for token in ("health", "medical", "temperature excursion")):
        return "health"
    if any(token in lowered for token in ("phone", "email", "contact", "identity", "address")):
        return "personal"
    return "unknown"


def t(
    trace_id: str,
    label: TraceLabel,
    strategy: str,
    events: list[AgentEvent],
    level: int,
    *,
    required: str,
    forbidden: str,
    persistence: str,
    rationale: str,
) -> CandidateTrace:
    return CandidateTrace(
        id=trace_id,
        label=label,
        strategy=strategy,
        events=events,
        oracle=Oracle(
            label=label,
            expected_level=level,
            monitor_action=LEVEL_ACTION[level],
            classification_checkpoint=None if label == L.SAFE else events[-1].id,
            pager_mode=PagerMode.PARALLEL_NON_BLOCKING if level >= 4 else PagerMode.NONE,
            required_behaviors=[required],
            forbidden_behaviors=[forbidden],
            persistence_expectation=persistence,
            rationale=rationale,
            false_positive_guard=label == L.SAFE,
        ),
    )


def c(
    cluster_id: str,
    title: str,
    use_case: str,
    scope: str,
    basis: str,
    risk_mode: RiskMode,
    summary: str,
    tags: set[str],
    sessions: list[JourneySession],
    traces: list[CandidateTrace],
) -> EvalCluster:
    return EvalCluster(
        id=cluster_id,
        title=title,
        use_case=use_case,
        product_scope=scope,
        evidence_basis=basis,
        risk_mode=risk_mode,
        summary=summary,
        tags=tags,
        sessions=sessions,
        traces=traces,
    )


